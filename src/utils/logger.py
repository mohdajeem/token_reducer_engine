# ==========================================================
# LOGGER
# ==========================================================

import logging

# ==========================================================
# LOGGER CONFIG
# ==========================================================

logging.basicConfig(

    level=logging.INFO,

    format=(

        "[%(levelname)s] "

        "%(name)s :: "

        "%(message)s"
    )
)

# ==========================================================
# ROOT LOGGER
# ==========================================================

logger = logging.getLogger(
    "semantic-reviewer"
)

# ==========================================================
# HELPERS
# ==========================================================

def set_debug():

    logger.setLevel(
        logging.DEBUG
    )

def set_info():

    logger.setLevel(
        logging.INFO
    )